"""Database access: Postgres in production, SQLite for local dev and tests.

Set DATABASE_URL (the Neon integration does this on Vercel) to use Postgres;
otherwise a local SQLite file is used. The app writes one dialect of SQL:
`?` placeholders (converted for Postgres), `RETURNING id` instead of
`lastrowid`, and `ON CONFLICT DO NOTHING`, all of which both databases support.
Money is always stored as integer cents.
"""
import os
import sqlite3
import threading
from contextlib import contextmanager
from typing import Iterator, Optional, Sequence, Set

import psycopg

DATABASE_URL: Optional[str] = os.environ.get("DATABASE_URL")
DB_PATH = os.environ.get("BANK_DB_PATH", "bank.db")

IntegrityError = (sqlite3.IntegrityError, psycopg.IntegrityError)

_TYPES = {
    "sqlite": {"id": "INTEGER PRIMARY KEY", "float": "REAL"},
    "postgres": {"id": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "float": "DOUBLE PRECISION"},
}

SCHEMA = """
CREATE TABLE IF NOT EXISTS customers (
    id          {id},
    name        TEXT NOT NULL,
    email       TEXT NOT NULL UNIQUE,
    plan        TEXT NOT NULL,
    created_at  {float} NOT NULL
);

-- Only a keyed hash of the secret is stored. `prefix` is a public lookup id.
CREATE TABLE IF NOT EXISTS api_keys (
    id            {id},
    customer_id   BIGINT NOT NULL REFERENCES customers(id),
    name          TEXT NOT NULL,
    prefix        TEXT NOT NULL UNIQUE,
    key_hash      TEXT NOT NULL,
    created_at    {float} NOT NULL,
    last_used_at  {float},
    revoked_at    {float}
);

CREATE TABLE IF NOT EXISTS accounts (
    id             {id},
    customer_id    BIGINT NOT NULL REFERENCES customers(id),
    name           TEXT NOT NULL,
    currency       TEXT NOT NULL DEFAULT 'USD',
    balance_cents  BIGINT NOT NULL CHECK (balance_cents >= 0)
);

CREATE TABLE IF NOT EXISTS transactions (
    id            {id},
    account_id    BIGINT NOT NULL REFERENCES accounts(id),
    amount_cents  BIGINT NOT NULL,           -- negative = debit
    description   TEXT NOT NULL,
    created_at    {float} NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_tx_account ON transactions(account_id, id DESC);

CREATE TABLE IF NOT EXISTS idempotency_keys (
    api_key_id      BIGINT NOT NULL,
    key             TEXT NOT NULL,
    request_hash    TEXT NOT NULL,
    status_code     INTEGER,                 -- NULL while the first request is in flight
    response_body   TEXT,
    created_at      {float} NOT NULL,
    PRIMARY KEY (api_key_id, key)
);

CREATE TABLE IF NOT EXISTS payouts (
    id             {id},
    account_id     BIGINT NOT NULL REFERENCES accounts(id),
    amount_cents   BIGINT NOT NULL,
    beneficiary    TEXT NOT NULL,
    status         TEXT NOT NULL,
    created_at     {float} NOT NULL,
    dispatch_at    {float} NOT NULL
);

CREATE TABLE IF NOT EXISTS usage_events (
    id           {id},
    api_key_id   BIGINT NOT NULL,
    customer_id  BIGINT NOT NULL,
    endpoint     TEXT NOT NULL,
    status_code  INTEGER NOT NULL,
    billable     INTEGER NOT NULL,
    day          TEXT NOT NULL,              -- UTC date, e.g. 2026-11-02
    created_at   {float} NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_usage_customer ON usage_events(customer_id, created_at);
"""


def schema_statements(dialect: str) -> list:
    sql = SCHEMA.format(**_TYPES[dialect])
    lines = [line for line in sql.splitlines() if not line.strip().startswith("--")]
    return [s.strip() for s in "\n".join(lines).split(";") if s.strip()]


class Database:
    """The small interface the app uses, identical for SQLite and Postgres."""

    def __init__(self, conn, dialect: str):
        self._conn = conn
        self.dialect = dialect

    def _sql(self, sql: str) -> str:
        return sql.replace("?", "%s") if self.dialect == "postgres" else sql

    def execute(self, sql: str, params: Sequence = ()):
        return self._conn.execute(self._sql(sql), tuple(params))

    def executemany(self, sql: str, rows: Sequence[Sequence]) -> None:
        if self.dialect == "postgres":
            with self._conn.cursor() as cur:
                cur.executemany(self._sql(sql), rows)
        else:
            self._conn.executemany(sql, rows)

    def begin(self) -> None:
        # SQLite: take the write lock up front so check-then-write can't interleave.
        self.execute("BEGIN IMMEDIATE" if self.dialect == "sqlite" else "BEGIN")

    def commit(self) -> None:
        self.execute("COMMIT")

    def rollback(self) -> None:
        self.execute("ROLLBACK")


# ---------- connections ----------

_initialized: Set[str] = set()
_init_lock = threading.Lock()
_pool = None


def configure(database_url: Optional[str] = None, path: Optional[str] = None) -> None:
    """Point the app at a different database (used by tests)."""
    global DATABASE_URL, DB_PATH, _pool
    if _pool is not None:
        _pool.close()
        _pool = None
    DATABASE_URL = database_url
    if path:
        DB_PATH = path


def _sqlite() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH, timeout=10, isolation_level=None, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def _postgres_pool():
    global _pool
    if _pool is None:
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        # A small pool per serverless instance. prepare_threshold=None keeps
        # psycopg compatible with Neon's PgBouncer (transaction pooling).
        _pool = ConnectionPool(
            DATABASE_URL, min_size=0, max_size=4, open=True,
            check=ConnectionPool.check_connection,
            kwargs={"autocommit": True, "row_factory": dict_row, "prepare_threshold": None},
        )
    return _pool


def _init_schema(db: Database) -> None:
    if db.dialect == "postgres":
        db.begin()
        db.execute("SELECT pg_advisory_xact_lock(727274)")  # one instance runs DDL at a time
        for stmt in schema_statements("postgres"):
            db.execute(stmt)
        db.commit()
    else:
        for stmt in schema_statements("sqlite"):
            db.execute(stmt)


@contextmanager
def connection() -> Iterator[Database]:
    if DATABASE_URL:
        with _postgres_pool().connection() as conn:
            db = Database(conn, "postgres")
            _ensure_schema(db, DATABASE_URL)
            yield db
    else:
        conn = _sqlite()
        try:
            db = Database(conn, "sqlite")
            _ensure_schema(db, DB_PATH)
            yield db
        finally:
            conn.close()


def _ensure_schema(db: Database, target: str) -> None:
    # Lazily, once per process: serverless platforms don't reliably run startup hooks.
    if target in _initialized:
        return
    with _init_lock:
        if target not in _initialized:
            _init_schema(db)
            _initialized.add(target)


def get_db() -> Iterator[Database]:
    """FastAPI dependency: one connection per request (autocommit mode)."""
    with connection() as db:
        yield db
